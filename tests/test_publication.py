    def test_frozen_opponent_packet_has_exact_source_not_private_worker_state(self):
        bot, task = self.envelope()
        packet = read_json(task['strategy']['opponents']['manifest'])
        for row in packet['opponents']:
            self.assertEqual(tree_hash(row['path']), row['source_hash'])
            self.assertEqual(sorted(p.name for p in Path(row['path']).rglob('*') if p.is_file()), ['main.cpp'])
        frozen = json.dumps(packet, sort_keys=True)
        other = 'beta' if bot == 'alpha' else 'alpha'
        self.commit(other, 'opponent changed while agent thinks')
        self.assertEqual(json.dumps(read_json(task['strategy']['opponents']['manifest']), sort_keys=True), frozen)
        self.assertNotIn('NOTES.md', frozen)
        self.assertNotIn('holdout', json.dumps(packet['opponents']))

    def recover_known_publication_failure(self, reason):
        from arena.protocol import encode_source
        from arena.publisher import recover_publication
        bot, task = self.envelope()
        config = self.owner_configs[bot]
        Path(config['attempts']).mkdir()
        attempt = make_attempt(config, task)
        (attempt / 'bots' / bot / 'src/main.cpp').write_text('synthetic valid candidate')
        (attempt / 'experiments' / bot / 'reference.cpp').write_text('source-level regression fixture')
        cache = attempt / 'experiments' / bot / '__pycache__'
        cache.mkdir()
        (cache / 'test.pyc').write_bytes(b'generated bytecode')
        result = self.final_result(bot, task)
        atomic_json(attempt / '.agent' / f"final-{task['task_id']}.json", result)
        payload = candidate_payload(config, attempt)
        self.assertFalse(any(name.endswith('.pyc') for name in payload['notes']))
        self.request(config, 'check', {'task_id': task['task_id'], 'source': payload['source']})
        self.arena.db.execute("UPDATE tasks SET state='PAUSED',result=? WHERE id=?", (json.dumps(result), task['task_id']))
        self.arena.db.execute("UPDATE workers SET state='PAUSED',detail=? WHERE id=?", (reason,bot))
        self.arena.db.put('paused', True)
        publication = recover_publication(self.arena, bot, payload)
        self.assertEqual(publication['new_model_invocations'], 0)
        self.assertEqual(self.arena.db.one('SELECT state FROM tasks WHERE id=?', (task['task_id'],))['state'], 'PUBLISHED')
        self.assertEqual(git(self.remote, 'show', f"{publication['commit']}:experiments/{bot}/reference.cpp"),
                         'source-level regression fixture')
        with self.assertRaises(ArenaError):
            recover_publication(self.arena, bot, payload)

